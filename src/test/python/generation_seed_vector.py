import hashlib
import struct


class JavaRandom:
    def __init__(self, seed):
        self.state = (seed ^ 0x5DEECE66D) & ((1 << 48) - 1)

    def bits(self, count):
        self.state = (self.state * 0x5DEECE66D + 0xB) & ((1 << 48) - 1)
        return self.state >> (48 - count)

    def unit(self):
        return ((self.bits(26) << 27) + self.bits(27)) / (1 << 53)


print("# Generated by src/test/python/generation_seed_vector.py; independent SHA-256/struct/LCG reference")
seeds = [0, 42, -1, -(1 << 63), (1 << 63) - 1, 42 + (1 << 48)]
print(f"count={len(seeds)}")
for index, seed in enumerate(seeds):
    prefix = f"vector.{index}"
    encoded = struct.pack(">4siq", b"GENS", 1, seed)
    print(f"{prefix}.seed={seed}")
    print(f"{prefix}.hex={encoded.hex()}")
    for label in ["attempt", "inheritance", "mutation", "frailty", "cosmetic"]:
        digest = hashlib.sha256(b"genesis:rng\0" + encoded + label.encode("ascii")).digest()
        derived = struct.unpack(">q", digest[:8])[0]
        print(f"{prefix}.{label}.seed={derived}")
        random = JavaRandom(derived)
        if label == "inheritance":
            print(f"{prefix}.{label}.bits=" + "".join(str(random.bits(1)) for _ in range(24)))
        elif label != "cosmetic":
            print(f"{prefix}.{label}.draw={random.unit()!r}")
